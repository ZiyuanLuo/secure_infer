#!/usr/bin/env bash
set -euo pipefail
ROOT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
cd "$ROOT_DIR"
if [[ -f .env ]]; then
  set -a
  source .env
  set +a
fi
export MODEL_PATH="${MODEL_OVERRIDE:-${MODEL_PATH:-}}"
export PYTHONPATH="${ROOT_DIR}${PYTHONPATH:+:${PYTHONPATH}}"
export ASCEND_RT_VISIBLE_DEVICES="${DEVICE_IDS:-0}"
export RUNTIME_RESULT_DIR="${RESULT_DIR:-runs/current}"
mkdir -p "$RUNTIME_RESULT_DIR"
export RUNTIME_COMPUTE_CHUNK="${COMPUTE_CHUNK:-1024}"
export RUNTIME_LOAD_CHUNK="${LOAD_CHUNK:-2048}"
export RUNTIME_NATIVE_MODE=native_secure
export PIPE_ENABLE_H2D="${ENABLE_H2D:-1}"
export PIPE_ENABLE_D2H="${ENABLE_D2H:-1}"
export PIPE_GHASH_AICPU_LIB="${GHASH_LIBRARY:-${PIPE_GHASH_AICPU_LIB:-${ROOT_DIR}/secure_infer/native/kernels/aicpu/build/libruntime_aicpu_ghash.so}}"
export PIPE_GCM_AIV_KEYSTREAM_LIB="${AIV_KEYSTREAM_LIBRARY:-${PIPE_GCM_AIV_KEYSTREAM_LIB:-}}"
if [[ "${SERVE_MODE:-runtime}" == runtime ]]; then
  export PIPE_CRYPTO_MODE=GCM
  export PIPE_GCM_H2D_LAYERWISE=0 PIPE_GCM_H2D_PIPELINE=1
  export PIPE_GCM_H2D_ASYNC_ADMISSION=0 PIPE_H2D_SYNC_EVERY_SLICE=0
  export PIPE_H2D_FORCE_SERIAL=0 PIPE_SERIAL_SYNC=1 PIPE_AICPU_AES_CTR=1
  export PIPE_TRANSFER_PREFETCH="${PIPE_TRANSFER_PREFETCH:-1}"
  export PIPE_PERIODIC_ADDRESS_PREDICTOR="${PIPE_PERIODIC_ADDRESS_PREDICTOR:-1}"
  export PIPE_PERIODIC_STRIDE_BOOTSTRAP="${PIPE_PERIODIC_STRIDE_BOOTSTRAP:-1}"
  export PIPE_PERIODIC_RUN_TRANSITION_CACHE="${PIPE_PERIODIC_RUN_TRANSITION_CACHE:-1}"
  export PIPE_SECURE_INFER_REPETITIVE_PREDICTOR=0
  export PIPE_LINEAR_PREFETCH_WINDOW="${PIPE_LINEAR_PREFETCH_WINDOW:-8}"
  export PIPE_GCM_CPU_PREENCRYPT="${PIPE_GCM_CPU_PREENCRYPT:-1}"
  export PIPE_GCM_KEYSTREAM_SCHEDULER="${PIPE_GCM_KEYSTREAM_SCHEDULER:-1}"
  export PIPE_NPU_KEYSTREAM_PREFETCH="${PIPE_NPU_KEYSTREAM_PREFETCH:-1}"
  export PIPE_GCM_PROFILE_TRUST_TAG=0 PIPE_GCM_DIRECT_VERIFIED_RELEASE=0
  export PIPE_D2H_ASYNC=1 PIPE_D2H_WRITE_BEHIND=1 PIPE_D2H_TWO_PHASE=1
  export PIPE_D2H_FUSED_GCM=1 PIPE_D2H_STAGE_PIPELINE=1
  if [[ "${ENABLE_H2D:-1}" != 0 || "${ENABLE_D2H:-1}" != 0 ]]; then
    [[ -f "$PIPE_GHASH_AICPU_LIB" ]] || {
      printf 'AES-GCM kernel not found: %s. Run ./configure.sh first.\n' "$PIPE_GHASH_AICPU_LIB" >&2
      exit 1
    }
  fi
  export LD_PRELOAD="${ROOT_DIR}/libsecure_infer.so${PIPE_EXTRA_PRELOAD:+:${PIPE_EXTRA_PRELOAD}}"
elif [[ "${SERVE_MODE}" != plain ]]; then
  printf 'SERVE_MODE 必须是 runtime 或 plain\n' >&2
  exit 1
fi
exec "${PYTHON:-python3}" -m secure_infer.serving.entrypoint "$@"
